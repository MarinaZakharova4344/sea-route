import { describe, expect, it } from "vitest";
import { diffDays, toDay, todayIso } from "./dates";
import { formatDate } from "./format";

// Часовой пояс компании по умолчанию: Москва (UTC+3)
describe("даты в часовом поясе компании", () => {
  it("ночью по Москве «сегодня» уже следующий день, хотя по UTC ещё вчера", () => {
    expect(todayIso(new Date("2026-10-20T22:30:00Z"))).toBe("2026-10-21");
    expect(todayIso(new Date("2026-10-20T20:59:00Z"))).toBe("2026-10-20");
  });

  it("момент времени переводится в день компании, простая дата не меняется", () => {
    expect(toDay("2026-10-20T22:30:00Z")).toBe("2026-10-21");
    expect(toDay("2026-10-20")).toBe("2026-10-20");
  });

  it("дата обновления на экране показывается по часовому поясу компании", () => {
    expect(formatDate("2026-10-23T21:20:00Z")).toBe("24.10.2026");
    expect(formatDate("2026-10-23")).toBe("23.10.2026");
  });

  it("«не обновлялась N дней» не сдвигается ночью: правка в 23:00 UTC и проверка в 01:00 по Москве", () => {
    // правка 20.10 в 23:00 UTC = 21.10 02:00 по Москве; проверка 21.10 в 02:00 UTC = 21.10 05:00 по Москве
    expect(diffDays("2026-10-20T23:00:00Z", todayIso(new Date("2026-10-21T02:00:00Z")))).toBe(0);
  });
});
